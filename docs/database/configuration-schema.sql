CREATE TABLE D2_CONFIGURATION.CONFIGURATION_VERSIONS (
    VERSION_ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY
        (START WITH 1 INCREMENT BY 1 MAXVALUE 9223372036854775807 NOCYCLE),
    VERSION_NUMBER NUMBER(10,0) NOT NULL,
    VERSION_LABEL VARCHAR2(100 CHAR) NOT NULL,
    PUBLICATION_STATE VARCHAR2(16 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR),
    IS_DEMONSTRATION NUMBER(1,0) NOT NULL,
    SCORE_POLICY_CODE VARCHAR2(16 CHAR) NOT NULL,
    MAX_FINAL_SCORE NUMBER(10,0),
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CREATED_BY_USER_ID NUMBER(19,0) NOT NULL,
    PUBLISHED_AT TIMESTAMP(6) WITH TIME ZONE,
    PUBLISHED_BY_USER_ID NUMBER(19,0),
    CONTENT_HASH CHAR(64),
    ROW_VERSION NUMBER(19,0) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_CFG_VERSIONS PRIMARY KEY (VERSION_ID)
        USING INDEX TABLESPACE USERS,
    CONSTRAINT UK_CFG_VERSION_NUMBER UNIQUE (VERSION_NUMBER)
        USING INDEX TABLESPACE USERS,
    CONSTRAINT CK_CFG_VERSION_ID CHECK
        (VERSION_ID BETWEEN 1 AND 9223372036854775807),
    CONSTRAINT CK_CFG_VERSION_NUMBER CHECK
        (VERSION_NUMBER BETWEEN 1 AND 2147483647),
    CONSTRAINT CK_CFG_VERSION_LABEL CHECK (TRIM(VERSION_LABEL) IS NOT NULL),
    CONSTRAINT CK_CFG_DEMO CHECK (IS_DEMONSTRATION IN (0,1)),
    CONSTRAINT CK_CFG_CREATED_USER CHECK
        (CREATED_BY_USER_ID BETWEEN 1 AND 9223372036854775807),
    CONSTRAINT CK_CFG_PUBLISHED_USER CHECK
        (PUBLISHED_BY_USER_ID IS NULL OR
         PUBLISHED_BY_USER_ID BETWEEN 1 AND 9223372036854775807),
    CONSTRAINT CK_CFG_ROW_VERSION CHECK
        (ROW_VERSION BETWEEN 0 AND 9223372036854775807),
    CONSTRAINT CK_CFG_SCORE_POLICY CHECK (
        (SCORE_POLICY_CODE = 'SUM' AND MAX_FINAL_SCORE IS NULL) OR
        (SCORE_POLICY_CODE = 'CAP_AT_MAX' AND MAX_FINAL_SCORE IS NOT NULL
         AND MAX_FINAL_SCORE BETWEEN 1 AND 2147483647)),
    CONSTRAINT CK_CFG_HASH CHECK
        (CONTENT_HASH IS NULL OR REGEXP_LIKE(CONTENT_HASH, '^[0-9A-Fa-f]{64}$')),
    CONSTRAINT CK_CFG_PUBLICATION CHECK (
        (PUBLICATION_STATE = 'DRAFT' AND PUBLISHED_AT IS NULL
         AND PUBLISHED_BY_USER_ID IS NULL AND CONTENT_HASH IS NULL) OR
        (PUBLICATION_STATE = 'PUBLISHED' AND PUBLISHED_AT IS NOT NULL
         AND PUBLISHED_BY_USER_ID IS NOT NULL AND CONTENT_HASH IS NOT NULL
         AND PUBLISHED_AT >= CREATED_AT))
) TABLESPACE USERS;

