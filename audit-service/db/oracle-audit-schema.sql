CREATE SEQUENCE AUD_AUDIT_EVENTS_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE AUD_AUDIT_EVENTS (
    AUDIT_EVENT_ID NUMBER(19) NOT NULL,
    PAYMENT_ID NUMBER(19),
    EVENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    RESOURCE_TYPE VARCHAR2(100 CHAR) NOT NULL,
    RESOURCE_ID VARCHAR2(100 CHAR) NOT NULL,
    ACTOR_ID VARCHAR2(100 CHAR),
    CORRELATION_ID VARCHAR2(100 CHAR),
    BEFORE_STATE CLOB,
    AFTER_STATE CLOB,
    METADATA CLOB,
    OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_AUD_AUDIT_EVENTS PRIMARY KEY (AUDIT_EVENT_ID)
);

CREATE INDEX IX_AUD_EVENT_RESOURCE ON AUD_AUDIT_EVENTS (RESOURCE_TYPE, RESOURCE_ID);
CREATE INDEX IX_AUD_EVENT_OCCURRED ON AUD_AUDIT_EVENTS (OCCURRED_AT);
CREATE INDEX IX_AUD_PAYMENT ON AUD_AUDIT_EVENTS (PAYMENT_ID);

CREATE OR REPLACE TRIGGER AUD_EVENTS_APPEND_ONLY
BEFORE UPDATE OR DELETE ON AUD_AUDIT_EVENTS
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'Audit events are append-only');
END;
